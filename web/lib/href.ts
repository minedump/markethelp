/**
 * Каким тегом рисовать ссылку.
 *
 * Внутри сайта переходы идут через next/link: он подхватывает страницу
 * заранее и меняет её без перезагрузки. Но так можно только по тем
 * адресам, у которых есть страница. Файл — прайс в PDF, картинка,
 * карточка организации — страницей не является: его отдаёт сервер,
 * и перехватывать нажатие по нему нечем. Такие ссылки, как и внешние,
 * рисуются обычным <a>.
 */

/** Адрес ведёт наружу сайта или открывает приложение телефона и почты. */
export function isExternal(href: string) {
  return /^(https?:|tel:|mailto:|#)/.test(href);
}

/** Адрес ведёт на файл: последний кусок пути с расширением. */
export function isFile(href: string) {
  const path = href.split(/[?#]/)[0];
  return /\.[a-z0-9]{2,5}$/i.test(path);
}

/** Ссылку рисуем обычным <a>, а не next/link. */
export function isPlain(href: string) {
  return isExternal(href) || isFile(href);
}
