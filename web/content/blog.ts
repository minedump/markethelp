/**
 * Написанные статьи.
 *
 * Каждую запись верстаем вручную, и пока написана одна — остальные
 * в списке есть, но ведут в никуда, поэтому карточка у них не ссылка.
 * Так в блоге видно, что готовится, и при этом не обещано того,
 * чего нет.
 *
 * illustration — картинка внутри текста: встаёт после раздела с этим
 * номером. results — таблица «было / стало» в конце разбора.
 */
export type Article = {
  /** обложка во всю ширину колонки */
  cover: string;
  coverAlt: string;
  sections: PostSection[];
  illustration?: { after: number; pic: string; alt: string; caption: string };
  results?: { after: number; head: [string, string, string]; rows: PostResult[] };
};

