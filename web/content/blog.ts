/** Написана ли статья: по этому карточка решает, быть ей ссылкой или нет. */
export function isWritten(slug: string) {
  return slug in ARTICLES;
}

/** Рубрики, за которыми есть записи: пустую вкладку не показываем. */
export function filledRubrics() {
  return BLOG_RUBRICS.filter(
    (r) => r.id === 'all' || POSTS.some((p) => p.rubric === r.id),
  );
}

