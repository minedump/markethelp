/**
 * Список того, что согласовать и предоставить перед запуском.
 *
 * Лежит на сайте отдельной страницей по прямой ссылке: так его можно
 * открыть с телефона на встрече, не пересылая файл и не заводя никому
 * доступов. Из поиска страница закрыта, в карту сайта не входит и
 * ниоткуда не связана ссылкой — найти её можно только зная адрес.
 *
 * `id` у пункта — ключ, под которым браузер помнит отметку. Он не
 * должен меняться вместе с текстом: поправили формулировку — отметки
 * остались на месте, переименовали `id` — все сняты. Поэтому id
 * короткие и смысловые, а не пронумерованные по порядку.
 *
 * Разметка внутри текста: `код` в обратных кавычках, больше ничего.
 * Ссылок здесь нет намеренно — список читают, а не ходят по нему.
 */

export type Owner = 'Разработчик' | 'Продукт менеджер' | 'Юрист';

export type Item = {
  id: string;
  /** Кто делает. Не ставится, когда исполнитель объявлен у раздела. */
  owner?: Owner;
  text: string;
  /** Где это стоит на сайте — для пунктов про заявленные цифры. */
  where?: string;
};

export type Table = { head: string[]; rows: string[][] };

export type Section = {
  id: string;
  title: string;
  /** Исполнитель на весь раздел — тогда у пунктов его не повторяем. */
  owner?: Owner;
  note?: string;
  items: Item[];
  /** Справочная таблица под списком: по ней отмечают, но не отмечается. */
  table?: Table;
};

